"""Regenerate ci/frozen-source.json for the current tree and write docs/CI_INVENTORY_CHANGE.md.

Deliberate, reviewable act (never run by CI): it hashes every tracked file outside ci/, .github/ and docs/ so that
`run_gates.frozen()` fails closed on any later product, test or lock change. The change report lists every addition, removal
and modification against the previous manifest, so an inventory change cannot be silent.

    python ci/freeze.py --previous OLD_MANIFEST.json
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
EXEMPT = ('ci/', '.github/', 'docs/')


def tracked():
    names = subprocess.check_output(['git', 'ls-files', '-z'], cwd=ROOT).decode().split('\0')
    return sorted(n for n in names if n and not n.startswith(EXEMPT) and (ROOT / n).is_file())


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--previous', type=Path, required=True)
    args = parser.parse_args()
    old = json.loads(args.previous.read_text())
    files = {n: hashlib.sha256((ROOT / n).read_bytes()).hexdigest() for n in tracked()}
    head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    manifest = dict(baseline=old['baseline'], regeneratedFrom='consolidated tree; see docs/CI_INVENTORY_CHANGE.md',
                    previousManifestFiles=len(old['files']), files=files)
    (ROOT / 'ci' / 'frozen-source.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    added = sorted(set(files) - set(old['files']))
    removed = sorted(set(old['files']) - set(files))
    changed = sorted(n for n in files if n in old['files'] and files[n] != old['files'][n])
    lines = ['# CI inventory change', '',
             f'Generated by `ci/freeze.py` against the parent commit `{head}` (product files hashed are the ones in that tree; later commits may change only `ci/`, `.github/` and `docs/`).',
             f'Previous manifest (`infra/phase31-ci-gates@04d974f`, baseline `{old["baseline"][:9]}`): {len(old["files"])} files. New manifest: {len(files)} files. '
             f'Added {len(added)}, removed {len(removed)}, modified {len(changed)}, unchanged {len(files) - len(added) - len(changed)}.', '',
             'Frozen-source semantics are unchanged: a tracked path outside `ci/`, `.github/`, `docs/` that is not in the manifest, or whose bytes differ, fails the run before any gate.', '']
    for title, names in (('Removed', removed), ('Added', added), ('Modified', changed)):
        lines += [f'## {title} ({len(names)})', ''] + [f'- `{n}`' for n in names] + ['']
    (ROOT / 'docs' / 'CI_INVENTORY_CHANGE.md').write_text('\n'.join(lines), encoding='utf-8')
    print(json.dumps(dict(files=len(files), added=len(added), removed=len(removed), changed=len(changed))))


if __name__ == '__main__':
    main()
